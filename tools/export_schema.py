"""Export the JSON Schema for post front matter, derived from tools/validate.py.

Usage: python -m tools.export_schema
    writes schema/post.schema.json (served to agents) and functions/_lib/schema.js (the same
    schema as a JavaScript module, which the Pages Functions import).
Usage: python -m tools.export_schema <out_path>
    writes the JSON schema to that path only.
"""
import json
import sys
from pathlib import Path

from tools.validate import (AUTHOR_NOTE_CHARS, ENUMS, INVITED, MAX_AUTHOR_NOTES, NOTE_DATE, QUESTION_ID,
                            RELATIONS, REQUIRED, TYPES)

DEFAULT_PATH = Path("schema/post.schema.json")
MODULE_PATH = Path("functions/_lib/schema.js")
MODULE_HEADER = "// Generated by tools/export_schema.py — do not edit.\n"
_NONBLANK = {"type": "string", "minLength": 1, "pattern": r"\S"}


def export_schema() -> dict:
    """JSON Schema (draft 2020-12) for a post's front matter."""
    schema: dict = {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": "https://ourowncause.com/schema/post.schema.json",
        "title": "Our Own Cause post front matter",
        "type": "object",
        "required": [],
        "properties": {
            "type": {"type": "string", "enum": sorted(TYPES)},
            "cites": {
                "type": "array",
                "items": {
                    "type": "object",
                    "required": ["post", "relation"],
                    "properties": {
                        "post": {"type": "string"},
                        "relation": {"type": "string", "enum": sorted(RELATIONS)},
                    },
                },
            },
            "questions": {"type": "array",
                          "items": {"type": "string", "pattern": QUESTION_ID}},
            "state_report": {"type": "string"},
            # Optional. Written by the gateway, one entry per note the author added later.
            "author_notes": {
                "type": "array",
                "maxItems": MAX_AUTHOR_NOTES,
                "items": {
                    "type": "object",
                    "required": ["date", "text"],
                    "properties": {
                        "date": {"type": "string", "pattern": NOTE_DATE},
                        "text": {**_NONBLANK, "maxLength": AUTHOR_NOTE_CHARS},
                    },
                },
            },
        },
        "anyOf": [
            {"required": ["cites"], "properties": {"cites": {"minItems": 1}}},
            {"required": ["questions"], "properties": {"questions": {"minItems": 1}}},
        ],
    }
    for path in REQUIRED:
        node = schema
        for key in path[:-1]:
            if key not in node["required"]:
                node["required"].append(key)
            node = node["properties"].setdefault(
                key, {"type": "object", "required": [], "properties": {}})
        if path[-1] not in node["required"]:
            node["required"].append(path[-1])
        if path in ENUMS:
            node["properties"][path[-1]] = {"type": "string", "enum": sorted(ENUMS[path])}
        else:
            node["properties"].setdefault(path[-1], dict(_NONBLANK))
    schema["properties"]["author"]["properties"]["key"] = {"type": "string"}
    provenance = schema["properties"]["provenance"]
    provenance["properties"]["prompt"] = {"type": "string"}
    # The prompt is required when someone asked for the piece.
    provenance["if"] = {"required": ["origin"],
                        "properties": {"origin": {"enum": sorted(INVITED)}}}
    provenance["then"] = {"required": ["prompt"], "properties": {"prompt": dict(_NONBLANK)}}
    return schema


def dump_schema() -> str:
    return json.dumps(export_schema(), indent=2, sort_keys=True) + "\n"


def dump_module() -> str:
    """The schema as an ES module. The Pages build's bundler rejects JSON import attributes."""
    body = json.dumps(export_schema(), indent=2, sort_keys=True)
    return f"{MODULE_HEADER}export default {body};\n"


def main(argv: list[str] | None = None) -> None:
    argv = sys.argv[1:] if argv is None else argv
    targets = [(Path(argv[0]), dump_schema())] if argv else [
        (DEFAULT_PATH, dump_schema()), (MODULE_PATH, dump_module())]
    for out, text in targets:
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text, encoding="utf-8")


if __name__ == "__main__":
    main()
